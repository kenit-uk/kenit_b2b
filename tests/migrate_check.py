"""예전 구조의 DB(역할 제약에 manager 없음, 이메일 필수, 로그인 번호 칸 없음)가 자동으로 바뀌는지 확인"""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from app import db as D

old = (D.SCHEMA.replace("('staff', 'manager', 'installer')", "('staff', 'installer')")
       .replace("email         TEXT UNIQUE {nocase},  -- 휴대폰으로만 가입한 사람은 비어 있음", "email         TEXT NOT NULL UNIQUE {nocase},")
       .replace("  phone_e164    TEXT,  -- 문자 로그인용 인증된 번호 (+447700900123)\n", ""))
assert "phone_e164" not in old and "'manager'" not in old
c = D.connect()
if c.pg:
    with c:
        c.raw.execute(old.format(pk="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", nocase=""))
else:
    c.raw.executescript(old.format(pk="INTEGER PRIMARY KEY AUTOINCREMENT", nocase="COLLATE NOCASE"))
with c:
    c.execute("INSERT INTO users (email, name, phone, password_hash, role, created_at) VALUES ('old@ex.com', 'Old', '07700 900123', 'x', 'staff', 'now')")
    c.execute("INSERT INTO users (email, name, phone, password_hash, role, created_at) VALUES ('old2@ex.com', 'Old2', '+44 7700 900123', 'x', 'installer', 'now')")
    c.execute("INSERT INTO houses (address, status, created_by, created_at, updated_at) VALUES ('Old house', '검토전', 1, 'now', 'now')")
try:
    with c:
        c.execute("INSERT INTO users (email, name, password_hash, role, created_at) VALUES ('m0@ex.com', 'M', 'x', 'manager', 'now')")
    raise SystemExit("old schema unexpectedly accepted manager")
except D.IntegrityError:
    pass
c.close()

D.init_db()   # 마이그레이션
D.init_db()   # 두 번 실행해도 문제없어야 함
c = D.connect()
with c:
    c.execute("INSERT INTO users (email, name, password_hash, role, created_at) VALUES ('m@ex.com', 'M', 'x', 'manager', 'now')")
    c.execute("INSERT INTO users (email, name, phone_e164, password_hash, role, created_at) VALUES (NULL, 'P', '+447700900999', '!', 'installer', 'now')")
    c.execute("INSERT INTO users (email, name, phone_e164, password_hash, role, created_at) VALUES (NULL, 'P2', '+447700900998', '!', 'installer', 'now')")
assert c.execute("SELECT COUNT(*) AS n FROM users").fetchone()["n"] == 5
assert c.execute("SELECT created_by FROM houses").fetchone()["created_by"] == 1            # 기존 데이터·참조 유지
phones = {r["name"]: r["phone_e164"] for r in c.execute("SELECT name, phone_e164 FROM users")}
assert phones["Old"] == "+447700900123" and phones["Old2"] is None, phones                  # 같은 번호는 한 명에게만
for bad in ["('z@ex.com', 'Z', NULL, 'x', 'owner', 'now')", "('y@ex.com', 'Y', '+447700900999', 'x', 'staff', 'now')"]:
    try:
        with c:
            c.execute(f"INSERT INTO users (email, name, phone_e164, password_hash, role, created_at) VALUES {bad}")
        raise SystemExit("constraint lost: " + bad)
    except D.IntegrityError:
        pass
h = c.execute("SELECT ref_no, stage, on_hold FROM houses").fetchone()
assert (h["ref_no"], h["stage"], h["on_hold"]) == ("WS-100001", 1, 0), dict(h)                       # 이전 상태 → 단계
members = [r["user_id"] for r in c.execute("SELECT user_id FROM house_members")]
assert members == [2], members                                                                       # 기존 설치업자 배정
if not c.pg:
    assert c.execute("PRAGMA foreign_key_check").fetchall() == []
print("MIGRATION OK", "(pg)" if c.pg else "(sqlite)")
