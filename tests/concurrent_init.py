"""서버리스 인스턴스 여러 개가 동시에 시작하는 상황: 예전 구조 DB에 init_db를 동시에 8번 실행해도 오류·중복 없이 한 번만 옮겨져야 한다."""
import os, sys, multiprocessing as mp
sys.path.insert(0, os.path.dirname(__file__))


def worker(q):
    try:
        from app import db as D
        D.init_db()
        q.put("ok")
    except Exception as e:
        q.put(f"{type(e).__name__}: {e}")


if __name__ == "__main__":
    from app import db as D
    c = D.connect()
    if not c.pg:
        print("CONCURRENT INIT SKIPPED (sqlite)"); sys.exit(0)
    old = (D.SCHEMA.replace("('staff', 'manager', 'installer')", "('staff', 'installer')")
           .replace("  ref_no          TEXT,           -- 관리번호 WS-100001\n  stage           INTEGER NOT NULL DEFAULT 1,\n  on_hold         INTEGER NOT NULL DEFAULT 0,\n", ""))
    assert "stage           INTEGER" not in old
    with c:
        c.raw.execute(old.format(pk="INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", nocase=""))
        c.execute("INSERT INTO users (email, name, password_hash, role, created_at) VALUES ('a@ex.com', 'A', 'x', 'staff', 'now')")
        c.execute("INSERT INTO users (email, name, password_hash, role, created_at) VALUES ('i@ex.com', 'I', 'x', 'installer', 'now')")
        for st in ["검토중", "설치완료", "보류"]:
            c.execute("INSERT INTO houses (address, status, created_by, created_at, updated_at) VALUES ('H', ?, 1, 'now', 'now')", (st,))
    c.close()
    q = mp.Queue()
    ps = [mp.Process(target=worker, args=(q,)) for _ in range(8)]
    [p.start() for p in ps]; [p.join(60) for p in ps]
    results = [q.get() for _ in ps]
    assert all(r == "ok" for r in results), results
    c = D.connect()
    rows = [(r["status"], r["stage"], r["on_hold"], r["ref_no"]) for r in c.execute("SELECT * FROM houses ORDER BY id")]
    assert rows == [("검토중", 3, 0, "WS-100001"), ("설치완료", 9, 0, "WS-100002"), ("보류", 1, 1, "WS-100003")], rows
    assert c.execute("SELECT COUNT(*) AS n FROM house_members").fetchone()["n"] == 3
    assert c.execute("SELECT COUNT(*) AS n FROM settings WHERE key LIKE ?", ("invite_code_%",)).fetchone()["n"] == 3
    print("CONCURRENT INIT OK (8 at once)")
